/**
 * Assemble editable HTML sections into the static page served from dist/.
 * Source of truth: src/index.template.html + src/sections.json + section files.
 * This runs in Node, never in the visitor's browser. No dependencies required.
 */
import {readFile, writeFile, rename} from 'node:fs/promises';
import {dirname, resolve, sep} from 'node:path';
import {fileURLToPath} from 'node:url';

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const sourceRoot = resolve(projectRoot, 'src');
const escapeHTML = value =>
  String(value).replace(
    /[&<>"']/g,
    character =>
      ({
        '&': '&amp;',
        '<': '&lt;',
        '>': '&gt;',
        '"': '&quot;',
        "'": '&#39;',
      })[character],
  );

// Exporting a pure assembly function lets checks cover section removal/reordering
// without modifying your real source files or generated page.
export async function assemblePage({template, sections, readSection}) {
  if (!Array.isArray(sections)) {
    throw new Error('src/sections.json must contain an array.');
  }
  const ids = new Set();
  const fragments = [];
  const links = [];
  for (const section of sections) {
    if (
      !section ||
      !/^[a-z][a-z0-9-]*$/.test(section.id) ||
      ids.has(section.id)
    ) {
      throw new Error(`Invalid or duplicate section ID: ${section?.id}`);
    }
    ids.add(section.id);
    if (section.enabled === false) {
      continue;
    }
    if (
      typeof section.file !== 'string' ||
      typeof section.label !== 'string' ||
      typeof section.fallback !== 'string'
    ) {
      throw new Error(
        `Section ${section.id} needs file, label, and fallback fields.`,
      );
    }
    const fragment = (await readSection(section.file)).trim();
    if (
      !new RegExp(`<section\\b[^>]*\\bid=["']${section.id}["']`).test(fragment)
    ) {
      throw new Error(
        `${section.file} must contain a section with id="${section.id}".`,
      );
    }
    fragments.push(fragment);
    links.push(
      `<a href="#${section.id}" data-i18n="${escapeHTML(section.label)}">${escapeHTML(section.fallback)}</a>`,
    );
  }
  let html = template;
  for (const [marker, content] of [
    ['SECTION_NAV', links.join('\n')],
    ['SECTIONS', fragments.join('\n\n')],
  ]) {
    const token = `<!-- ${marker} -->`;
    if (html.split(token).length !== 2) {
      throw new Error(`Template must contain exactly one ${token} marker.`);
    }
    html = html.replace(new RegExp(`^[ \\t]*${token}`, 'm'), line => {
      const indent = line.slice(0, line.indexOf('<'));
      return content
        .split('\n')
        .map(text => (text ? indent + text : ''))
        .join('\n');
    });
  }
  return (
    '<!-- Generated by scripts/build.mjs. Edit src/ files, then run npm run build. -->\n' +
    html.trim() +
    '\n'
  );
}

export async function build() {
  const template = await readFile(
    resolve(sourceRoot, 'index.template.html'),
    'utf8',
  );
  const sections = JSON.parse(
    await readFile(resolve(sourceRoot, 'sections.json'), 'utf8'),
  );
  const html = await assemblePage({
    template,
    sections,
    readSection: async file => {
      const path = resolve(sourceRoot, file);
      if (!path.startsWith(sourceRoot + sep)) {
        throw new Error('Section files must stay inside src/.');
      }
      return readFile(path, 'utf8');
    },
  });
  const output = resolve(projectRoot, 'dist/index.html');
  // Replace only once assembly succeeds; errors leave the last good page intact.
  // Separate preview and manual builds must not share a temporary file.
  const temporary = `${output}.${process.pid}.tmp`;
  await writeFile(temporary, html);
  await rename(temporary, output);
  console.log(
    `Built dist/index.html (${sections.filter(section => section.enabled !== false).length} sections).`,
  );
}

if (
  process.argv[1] &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  await build();
}
